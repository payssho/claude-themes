// Writes the city as a still SVG. Every animation is paused where its delay
// puts it, so each light keeps its own brightness and each billboard its own
// colour, and the metros stop on their lines. Edges are made crisp
// everywhere for the pixel-art look.
//
//   node tools/export-svg.mjs <out.svg>      the SVG alone (render.py uses it)
//   node tools/export-svg.mjs <out.js>       a module the plugin imports,
//                                            exporting it as SCENE
//
// The plugin hands the SVG to the app, which draws it as a plain picture:
// nothing to animate, nothing to redraw. The app takes at most 131,072
// characters, which this checks.

import { writeFileSync } from 'node:fs'

import { SCENE } from './scene.js'

const out = process.argv[2]
if (!out) {
  console.error('usage: node tools/export-svg.mjs <out.svg | out.js>')
  process.exit(1)
}

const FREEZE = '<style>*{animation-play-state:paused!important;shape-rendering:crispEdges!important}</style>'
const svg = SCENE.replace('</style>', `</style>${FREEZE}`)

if (out.endsWith('.js')) {
  if (svg.length > 131072) {
    console.error(`The scene is ${svg.length} characters; the app takes at most 131072.`)
    process.exit(1)
  }
  writeFileSync(
    out,
    '// Generated by tools/export-svg.mjs from tools/scene.js: edit those, then run\n' +
      '//   node night-theme/tools/export-svg.mjs night-theme/hooks/scene.js\n' +
      `export const SCENE = ${JSON.stringify(svg)}\n`,
  )
  console.log(`${out}: ${svg.length} characters`)
} else {
  writeFileSync(out, svg)
}
